import { Component, inject, signal } from '@angular/core';
import { FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { MatButtonModule } from '@angular/material/button';
import { provideNativeDateAdapter } from '@angular/material/core';
import { MatDatepickerModule } from '@angular/material/datepicker';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatIconModule } from '@angular/material/icon';
import { MatInputModule } from '@angular/material/input';
import { MatProgressSpinnerModule } from '@angular/material/progress-spinner';
import { MatSnackBar } from '@angular/material/snack-bar';
import { ActivatedRoute, Router } from '@angular/router';
import { ProjectFacade } from '../project-facade';
import type { Project } from '../project.model';

type CreateProjectState = 'idle' | 'loading';

@Component({
  selector: 'app-create-project',
  imports: [
    MatFormFieldModule,
    MatInputModule,
    ReactiveFormsModule,
    MatButtonModule,
    MatDatepickerModule,
    MatProgressSpinnerModule,
    MatIconModule,
  ],
  templateUrl: './create-project.html',
  styleUrl: './create-project.scss',
  providers: [provideNativeDateAdapter()],
})
export class CreateProject {
  private readonly _router = inject(Router);
  private readonly _route = inject(ActivatedRoute);
  private readonly _projectFacade = inject(ProjectFacade);
  private readonly _snackBar = inject(MatSnackBar);

  createProjectState = signal<CreateProjectState>('idle');

  projectForm = new FormGroup({
    name: new FormControl('', Validators.required),
    description: new FormControl(''),
    deadline: new FormControl('', Validators.required),
  });

  openSnackBar(message: string): void {
    const snackbarRef = this._snackBar.open(message, 'Dismiss', {
      duration: 5000,
    });

    snackbarRef.onAction().subscribe(() => {
      snackbarRef.dismiss();
    });
  }

  async onSubmit(): Promise<void> {
    const projectForm = this.projectForm;

    if (!projectForm.valid) {
      console.error('Project form is invalid');
      return;
    }

    const formResult = this.projectForm.getRawValue();
    const name = formResult.name ?? '';
    const description = formResult.description ?? '';
    const deadline = formResult.deadline ?? '';

    // Prepare the project data, excluding the 'id' which will be generated by the backend
    const projectData: Omit<Project, 'id'> = {
      name,
      description,
      deadline,
    };
    this.createProjectState.set('loading');

    try {
      // Add the project using the facade and get the generated project ID
      const projectId = await this._projectFacade.addProject(projectData);

      // Reset the form
      this.projectForm.reset();

      // NOTE: Assumption for the navigation is that the parent is the project dashboard component route.
      // if this is violated -> change the `relativeTo` to align it
      // or make the path explicit
      this._router.navigate([projectId], { relativeTo: this._route.parent });
    } catch (error) {
      console.error('Error creating project:', error);

      // Reset the form
      this.projectForm.reset();

      this.createProjectState.set('idle');
      this.openSnackBar('Project creation failed');
    }
  }

  onBack(): void {
    this._router.navigate([''], { relativeTo: this._route });
  }
}
